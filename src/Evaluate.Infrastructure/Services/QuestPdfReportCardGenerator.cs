using Evaluate.Application.Common.Interfaces;
using Evaluate.Application.Evaluations.Queries.GetStudentReportCard;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Evaluate.Infrastructure.Services;

public class QuestPdfReportCardGenerator : IReportCardPdfGenerator
{
    private const string Purple = "#6F63D9";
    private const string PurpleLight = "#8B7FE8";
    private const string PurplePale = "#EFECFD";
    private const string Text = "#2C3145";
    private const string Muted = "#9096A8";
    private const string Border = "#EDEFF5";

    private static readonly (string Grade, string Range)[] GradingScale =
    [
        ("A", "90 - 100"),
        ("B", "80 - 89"),
        ("C", "70 - 79"),
        ("D", "60 - 69"),
        ("F", "Below 60"),
    ];

    public byte[] Generate(ReportCardDto reportCard)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(24);
                page.DefaultTextStyle(x => x.FontSize(10).FontColor(Text));

                page.Content()
                    .Border(1).BorderColor(Border)
                    .Padding(6)
                    .Border(2).BorderColor(Purple)
                    .Padding(20)
                    .Column(column =>
                    {
                        column.Item().Element(c => Header(c, reportCard));
                        column.Item().PaddingTop(18).Element(c => StudentInfo(c, reportCard));
                        column.Item().PaddingTop(16).Element(c => GradingScaleBox(c));

                        if (reportCard.Courses.Count == 0)
                        {
                            column.Item().PaddingTop(16).Text("No finalized evaluations recorded for this term yet.").FontColor(Muted);
                        }
                        else
                        {
                            foreach (var course in reportCard.Courses)
                            {
                                column.Item().PaddingTop(16).Element(c => CourseSection(c, course));
                            }
                        }

                        column.Item().PaddingTop(24).Element(SignatureRow);
                    });

                page.Footer().PaddingTop(8).AlignCenter().Text(text =>
                {
                    text.Span("Generated by Evaluate — ").FontColor(Muted).FontSize(8);
                    text.Span(DateTime.Now.ToString("MMMM d, yyyy")).FontColor(Muted).FontSize(8);
                });
            });
        });

        return document.GeneratePdf();
    }

    private static void Header(IContainer container, ReportCardDto reportCard)
    {
        container.Row(row =>
        {
            row.AutoItem().Height(44).Width(44)
                .Background(Purple)
                .AlignMiddle().AlignCenter()
                .Text("E").FontSize(20).Bold().FontColor(Colors.White);

            row.RelativeItem().PaddingLeft(10).AlignMiddle().Column(brandColumn =>
            {
                brandColumn.Item().Text("Evaluate School").FontSize(15).Bold();
                brandColumn.Item().Text("Student Progress Report").FontSize(9).FontColor(Muted);
            });

            row.AutoItem().AlignMiddle()
                .Background(Purple)
                .Padding(10)
                .Text("REPORT CARD").FontSize(13).Bold().FontColor(Colors.White);
        });
    }

    private static void StudentInfo(IContainer container, ReportCardDto reportCard)
    {
        container.Background(PurplePale).Padding(14).Row(row =>
        {
            row.RelativeItem().Column(left =>
            {
                left.Item().Element(c => InfoField(c, "Name of Student", reportCard.StudentName));
                left.Item().PaddingTop(8).Element(c => InfoField(c, "Student Number", reportCard.StudentNumber));
            });
            row.RelativeItem().Column(right =>
            {
                right.Item().Element(c => InfoField(c, "Class", reportCard.ClassName));
                right.Item().PaddingTop(8).Element(c => InfoField(c, "Term", $"{reportCard.TermName}, {reportCard.AcademicYearName}"));
            });
        });

        static void InfoField(IContainer c, string label, string value) => c.Column(col =>
        {
            col.Item().Text(label.ToUpperInvariant()).FontSize(7.5f).FontColor(Muted).LetterSpacing(0.05f);
            col.Item().PaddingTop(2).Text(value).FontSize(11).SemiBold();
        });
    }

    private static void GradingScaleBox(IContainer container)
    {
        container.Column(column =>
        {
            column.Item().Background(Purple).Padding(6).Text("Grading Scale").FontColor(Colors.White).SemiBold().FontSize(9);
            column.Item().Border(1).BorderColor(Border).Padding(8).Row(row =>
            {
                foreach (var (grade, range) in GradingScale)
                {
                    row.RelativeItem().AlignCenter().Column(col =>
                    {
                        col.Item().AlignCenter().Text(grade).Bold().FontSize(12).FontColor(Purple);
                        col.Item().AlignCenter().Text(range).FontSize(7.5f).FontColor(Muted);
                    });
                }
            });
        });
    }

    private static void CourseSection(IContainer container, CourseReportDto course)
    {
        container.Column(column =>
        {
            column.Item().Background(Purple).Padding(6).Row(row =>
            {
                row.RelativeItem().Text(course.CourseName).FontColor(Colors.White).SemiBold().FontSize(10);
                if (course.FinalGrade is not null && course.FinalPercentage is not null)
                {
                    row.AutoItem().Text($"{course.FinalGrade}  ({course.FinalPercentage:0.#}%)").FontColor(Colors.White).SemiBold().FontSize(10);
                }
            });

            column.Item().Border(1).BorderColor(Border).BorderTop(0).Padding(10).Column(body =>
            {
                body.Item().Table(table =>
                {
                    table.ColumnsDefinition(columns =>
                    {
                        columns.RelativeColumn(2);
                        columns.RelativeColumn(1);
                        columns.RelativeColumn(3);
                    });

                    table.Header(header =>
                    {
                        header.Cell().Element(HeaderCell).Text("Topic");
                        header.Cell().Element(HeaderCell).Text("Score");
                        header.Cell().Element(HeaderCell).Text("Comment");

                        static IContainer HeaderCell(IContainer c) => c
                            .BorderBottom(1).BorderColor(Muted)
                            .PaddingBottom(4)
                            .DefaultTextStyle(x => x.SemiBold().FontSize(8.5f).FontColor(Muted));
                    });

                    foreach (var topic in course.Topics)
                    {
                        table.Cell().Element(BodyCell).Text(topic.TopicName);
                        table.Cell().Element(BodyCell).Text($"{topic.Score:0.#}%");
                        table.Cell().Element(BodyCell).Text(topic.Comment ?? "—").FontColor(topic.Comment is null ? Muted : Text);

                        static IContainer BodyCell(IContainer c) => c
                            .BorderBottom(1).BorderColor(Border)
                            .PaddingVertical(5);
                    }
                });

                if (!string.IsNullOrWhiteSpace(course.OverallComments))
                {
                    body.Item().PaddingTop(8).Background(PurplePale).Padding(8).Text(text =>
                    {
                        text.Span("Teacher's Comment: ").SemiBold().FontColor(Purple);
                        text.Span(course.OverallComments);
                    });
                }
            });
        });
    }

    private static void SignatureRow(IContainer container)
    {
        container.PaddingTop(12).Row(row =>
        {
            row.RelativeItem().Column(col =>
            {
                col.Item().PaddingTop(20).LineHorizontal(1).LineColor(Muted);
                col.Item().PaddingTop(3).Text("Class Teacher's Signature").FontSize(8).FontColor(Muted);
            });
            row.ConstantItem(30);
            row.RelativeItem().Column(col =>
            {
                col.Item().PaddingTop(20).LineHorizontal(1).LineColor(Muted);
                col.Item().PaddingTop(3).Text("Parent / Guardian Signature").FontSize(8).FontColor(Muted);
            });
        });
    }
}
